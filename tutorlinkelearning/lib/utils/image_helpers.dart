// A 1x1 transparent PNG, used when a record has no image yet so the widget
// tree still gets a valid provider instead of throwing.
final _transparentPixel = MemoryImage(Uint8List.fromList(const [
  0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A, //
  0x00, 0x00, 0x00, 0x0D, 0x49, 0x48, 0x44, 0x52,
  0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01,
  0x08, 0x06, 0x00, 0x00, 0x00, 0x1F, 0x15, 0xC4,
  0x89, 0x00, 0x00, 0x00, 0x0A, 0x49, 0x44, 0x41,
  0x54, 0x78, 0x9C, 0x63, 0x00, 0x01, 0x00, 0x00,
  0x05, 0x00, 0x01, 0x0D, 0x0A, 0x2D, 0xB4, 0x00,
  0x00, 0x00, 0x00, 0x49, 0x45, 0x4E, 0x44, 0xAE,
  0x42, 0x60, 0x82,
]));

// Locally-picked profile photos are kept as on-device file paths (no
// Storage upload to point a NetworkImage at); seeded/placeholder images
// stay as network URLs.
ImageProvider appImageProvider(String source) {
  if (source.isEmpty) {
    return _transparentPixel;
  }
  if (source.startsWith('http')) {
    return NetworkImage(source);
  }
  return FileImage(File(source));
}
